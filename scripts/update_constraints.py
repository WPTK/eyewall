"""Regenerate scripts/binary-constraints.txt, the pins the standalone binaries are built with.

    python scripts/update_constraints.py          # rewrite the file
    python scripts/update_constraints.py --check  # exit 1 if the file is out of date (no network change, just a diff)

The binaries.yml jobs and scripts/build_exe.ps1 install with `-c scripts/binary-constraints.txt`, so a build next month
uses the versions a build today does. The resolver runs once per release platform (pip's dry-run report, wheels only,
Python 3.12 as shipped) and the results are merged: one version per package, or this script stops and says which
platforms disagree. PyInstaller itself is left out; scripts/pyinstaller-version.txt stays its one source. Refresh before
a release when the dependency ranges in pyproject.toml allow something newer, and commit the diff.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "scripts" / "binary-constraints.txt"
# Pip platform tags (comma separated) per release binary. The Linux ones stand in for the python:3.12-bullseye
# container, whose glibc 2.31 takes manylinux_2_28 wheels.
PLATFORMS = (
    "win_amd64",
    "manylinux_2_28_x86_64,manylinux2014_x86_64,manylinux_2_17_x86_64",
    "manylinux_2_28_aarch64,manylinux2014_aarch64,manylinux_2_17_aarch64",
    "macosx_11_0_arm64",
    "macosx_10_13_x86_64",
)
PYTHON_VERSION = "3.12"
SKIP = {"pyinstaller"}


def requirements() -> list[str]:
    """What the binary jobs install: the package's dependencies, tzdata, textual-image and PyInstaller."""
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    pin = (ROOT / "scripts" / "pyinstaller-version.txt").read_text(encoding="utf-8").strip()
    deps = [d.split(";")[0].strip() for d in project["dependencies"]]
    # PyInstaller needs pefile and pywin32-ctypes on Windows and macholib on macOS; pip tests those markers against the
    # machine running this script, so name them outright and the output is the same wherever it is regenerated.
    return [*deps, "tzdata", "textual-image", f"pyinstaller=={pin}", "pefile", "pywin32-ctypes", "macholib"]


def resolve(platform: str, reqs: list[str]) -> dict[str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        tags = [arg for tag in platform.split(",") for arg in ("--platform", tag)]
        command = [
            sys.executable, "-m", "pip", "install", "--dry-run", "--quiet", "--ignore-installed",
            "--report", str(report), "--target", str(Path(tmp) / "target"),
            *tags, "--python-version", PYTHON_VERSION, "--implementation", "cp",
            "--only-binary=:all:", *reqs,
        ]  # fmt: skip
        subprocess.run(command, check=True)
        data = json.loads(report.read_text(encoding="utf-8"))
    pins = {}
    for item in data["install"]:
        meta = item["metadata"]
        name = meta["name"].lower().replace("_", "-")
        if name not in SKIP:
            pins[name] = meta["version"]
    return pins


def render() -> str:
    reqs = requirements()
    merged: dict[str, dict[str, str]] = {}
    for platform in PLATFORMS:
        for name, version in resolve(platform, reqs).items():
            merged.setdefault(name, {})[platform] = version
    lines = []
    for name in sorted(merged):
        versions = set(merged[name].values())
        if len(versions) != 1:
            sys.exit(f"{name} resolves to different versions per platform: {merged[name]}")
        lines.append(f"{name}=={versions.pop()}")
    header = (
        "# Generated by scripts/update_constraints.py; do not edit by hand.\n"
        "# Pins for the standalone binaries (binaries.yml, scripts/build_exe.ps1). PyInstaller is pinned in\n"
        "# scripts/pyinstaller-version.txt. Platform-only packages (tzdata, pefile, macholib) are listed too.\n"
    )
    return header + "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the file is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.name} is out of date; run python scripts/update_constraints.py")
            return 1
        print(f"{OUTPUT.name} is current")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(text.splitlines()) - 3} pins)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
